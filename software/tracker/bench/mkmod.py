#!/usr/bin/env python3
"""mkmod.py - generate Tracker / MOD player tables for 6309 assembly.

    python3 bench/mkmod.py [CMDSDIR]

Reads the canonical period table from hardware/audio/refplayer/period_table.c
and generates modtab.inc (period table, tempo table, vibrato sine table,
and volume saturation table) into CMDSDIR (default ../nitros9/level2/arm6309/cmds).
"""

import os
import sys
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
DEFAULT_CMDSDIR = os.path.join(ROOT, "..", "nitros9", "level2", "arm6309", "cmds")


def generate_tables(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "modtab.inc")

    ref_c = os.path.join(ROOT, "hardware", "audio", "refplayer", "period_table.c")
    if not os.path.isfile(ref_c):
        sys.exit(f"FAIL: {ref_c} not found")

    src = open(ref_c, "r", encoding="utf-8").read()
    body = src[src.index("mod_protracker_period_table") :]
    body = body[body.index("{") + 1 :]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    nums = [int(v) for v in re.findall(r"\b\d+\b", body[: body.index("};")])]

    if len(nums) != 16 * 36:
        sys.exit(f"FAIL: period_table.c gave {len(nums)} numbers, expected 576 (16*36)")

    out = [
        "********************************************************************",
        "* modtab.inc - ProTracker period, tempo, vibrato, and volume tables",
        "* Generated by software/tracker/bench/mkmod.py from period_table.c",
        "********************************************************************",
        "",
        "* ProTracker period table: 16 finetune rows x 36 notes (C-1..B-3)",
        "ptab",
    ]

    for r in range(16):
        row = nums[r * 36 : (r + 1) * 36]
        out.append(f"* Finetune {r if r <= 7 else r - 16:+d} (row {r})")
        for k in range(0, 36, 12):
            out.append("        fdb     " + ",".join(str(v) for v in row[k : k + 12]))

    out.extend(
        [
            "",
            "* CIA-B tempo reload values: 1773447 / BPM (BPM 0 treated as 125)",
            "* Timer counts color clock / 5 (709.379 kHz). 50.002 Hz at 125 BPM ($376B = 14187).",
            "tempotab",
        ]
    )

    vals = [1773447 // (b if b else 125) for b in range(256)]
    vals = [v & 0xFFFF for v in vals]
    for k in range(0, 256, 8):
        out.append("        fdb     " + ",".join(f"${v:04X}" for v in vals[k : k + 8]))

    out.extend(
        [
            "",
            "* ProTracker vibrato / tremolo sine wave (32 entries, half period)",
            "vibsine",
            "        fcb     0,24,49,74,97,120,141,161",
            "        fcb     180,197,212,224,235,244,250,253",
            "        fcb     255,253,250,244,235,224,212,197",
            "        fcb     180,161,141,120,97,74,49,24",
            "",
            "* Volume expansion table: Paula 0..64 -> 8-bit DAC code 0..255",
            "* 4 * vol, with 64 saturated to 255. Eliminates 12 dB volume loss.",
            "volcode",
        ]
    )

    vol_codes = [min(255, v * 4) for v in range(65)]
    for k in range(0, 65, 8):
        chunk = vol_codes[k : k + 8]
        out.append("        fcb     " + ",".join(str(c) for c in chunk))

    open(out_file, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"Generated {out_file} ({len(nums)} periods, 256 tempos, 32 sines, 65 volumes)")


if __name__ == "__main__":
    target_dir = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CMDSDIR
    generate_tables(target_dir)
