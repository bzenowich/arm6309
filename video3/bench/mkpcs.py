#!/usr/bin/env python3
"""mkpcs.py - generate `pcs`'s data from Bill Budge's original sources.

    python3 video3/bench/mkpcs.py [CMDSDIR]

Writes, beside this script:

    pcs.pal      512 bytes, big-endian RGB565 (kept as a file so the palette
                 can be eyeballed; pcsdat.asm also carries it inline)
    pcs.png      a 1:1 preview of the artwork and the screen layout
    pcsdat.asm   -> CMDSDIR (default ../nitros9/level2/arm6309/cmds)

⭐ THE POINT OF THIS SCRIPT IS THAT IT INVENTS ALMOST NOTHING.  The port claims
to *be* Pinball Construction Set, not to resemble it, and the whole of that
claim rests on the artwork, the 43 part templates, the four World tuning
tables, the seven cosine tables, the slope quantiser, the scoring tables, the
sound effects and the proportional font all coming out of `reference/pcs/`
rather than out of somebody's judgement.  What this script does add is:

  - the PALETTE (pcspal.py), because the original had two colours;
  - the 2x DOUBLING, because the screen is 640x480 and the original 320x192;
  - the 160 x 240 world, 48 rows taller than the Atari's 160 x 192, which is
    the one gameplay-visible decision in the port (video3/docs/pcs.md 3).

Everything else is transcription, and `pcsasm.py`/`pcsparts.py` check their own
transcription against a second statement of the same fact wherever the sources
make one.
"""

