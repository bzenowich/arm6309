    _fcb(o, pcspal.blob())
    w('')
    w('* ══════════════════ THE FONT ══════════════════════════════════════')
    w('* CDRAW.s:853 - 36 glyphs, 7 rows x 1 byte, proportional (CWIDTH).')
    w('* Doubled: %d rows x %d bytes a glyph, %d pixels wide.'
      % (7 * SCALE, SCALE, 8 * SCALE))
    w('PC.Glyphs           equ       36')
    w('PC.GlyphH           equ       %d' % (7 * SCALE))
    w('PC.GlyphW           equ       %d         bytes a row' % SCALE)
    w('PC.GlyphSz          equ       %d' % (7 * SCALE * SCALE))
    w('')
    w('PCFntW              equ       *         advance in card pixels, 37 entries')
    _fcb(o, cw)
    w('')
    w('PCFont              equ       *')
    for g, bits in enumerate(glyphs):
        ch = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'[g]
        w('* %s' % ch)
        _fcb(o, bits)
    w('')
    w('* ══════════════════ THE ARTWORK ═══════════════════════════════════')
    w('* BITMAPS.OBJ, cut by the EQU chain at RUN.s:100-118, with every XOR')
    w('* animation accumulated back into standalone pictures and doubled.')
    w('* ⛔ The frames ARE deltas in the original; a machine with no')
    w('* read-modify-write needs pictures (pcsparts.py says how).')
