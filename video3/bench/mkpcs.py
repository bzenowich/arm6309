    w('* ⛔ EVERY BYTE VERBATIM FROM RUN.s AND PPAK.s.  Nothing here is')
    w('* recomputed - checkpcs.py compares the 6809 against a Python model of')
    w('* the same arithmetic, and a table regenerated by one and read by the')
    w('* other is the check answering its own question.')
