    w('* ⚠ SCORETBL, SOUNDTBL, EFFECTS and NOTES ARE EMITTED BY physics_tables()')
    w('* BELOW, as PCSCORETBL, PCSOUNDTBL, PCEFFECTS and PCNOTES.  They were')
